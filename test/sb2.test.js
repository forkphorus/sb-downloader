import {test, mock} from 'node:test';
import assert from 'node:assert/strict';
import fs from 'node:fs';
import JSZip from '@turbowarp/jszip';
import * as SBDL from '../src/export-node.js';
import {getFixturePath} from './test-utilities.js';

test('sb2 project from JSON', {timeout: 30000}, async (t) => {
  const fixture = getFixturePath('sb2-167118244.json');
  const project1 = await SBDL.downloadProjectFromJSON(fs.readFileSync(fixture, 'utf-8'));
  const project2 = await SBDL.downloadProjectFromJSON(JSON.parse(fs.readFileSync(fixture, 'utf-8')));
  const project3 = await SBDL.downloadProjectFromBuffer(fs.readFileSync(fixture));
  assert.equal(project1.type, 'sb2');
  assert.equal(project1.title, '');
  assert.ok(project1.arrayBuffer instanceof ArrayBuffer);
  // All methods of loading the project should result in identical data
  assert.deepEqual(project1, project2);
  assert.deepEqual(project2, project3);
  // The data should not change unexpectedly
  t.assert.snapshot(project1);
});

test('sb2 project from sb2', async () => {
  const fixture = getFixturePath('167118244.sb2');
  const originalData = fs.readFileSync(fixture);
  const project = await SBDL.downloadProjectFromBuffer(originalData);
  assert.equal(project.type, 'sb2');
  assert.equal(project.title, '');
  assert.deepEqual(new Uint8Array(project.arrayBuffer), new Uint8Array(originalData.buffer));
});

test('sb2 with non-standard JSON', {timeout: 30000}, async () => {
  for (const fixture of [getFixturePath('non-standard-json-sb2.json'), getFixturePath('non-standard-json.sb2')]) {
    const processJSON = mock.fn((type, data) => {
      assert.equal(type, 'sb2');
      assert.equal(data.variables[0].value, NaN);
      assert.equal(data.variables[1].value, Infinity);
      return {
        something: [Infinity, -Infinity, NaN]
      };
    });
    const project = await SBDL.downloadProjectFromBuffer(fs.readFileSync(fixture), {
      processJSON
    });
    assert.equal(processJSON.mock.callCount(), 1);
    const zip = await JSZip.loadAsync(project.arrayBuffer);
    assert.equal(await zip.file('project.json').async('text'), '{"something":[Infinity,-Infinity,NaN]}');
  }
});

test('sb2 with missing assets', async (t) => {
  const data = fs.readFileSync(getFixturePath('missing-assets.sb2'));
  let loadedAssets = -1;
  let totalAssets = -1;
  const project = await SBDL.downloadProjectFromBuffer(data, {
    onProgress: (type, loaded, total) => {
      if (type === 'assets') {
        loadedAssets = loaded;
        totalAssets = total;
      }
    }
  });
  assert.equal(loadedAssets, 5);
  assert.equal(totalAssets, 5);
  t.assert.snapshot(project.arrayBuffer);

  // Even though it was rezipped, project.json should not change
  const zip = await JSZip.loadAsync(project.arrayBuffer);
  const text = await zip.file('project.json').async('text');
  assert.equal(text.includes('// Comment that shouldn\'t be removed :)\n'), true);
});

test('sb2 generated by tosh', async () => {
  const data = fs.readFileSync(getFixturePath('tosh-default.sb2'));
  const progressEvents = [];
  const project = await SBDL.downloadProjectFromBuffer(data, {
    onProgress: (type) => {
      progressEvents.push(type);
    }
  });

  assert.equal(progressEvents.includes('assets'), false);

  const zip = await JSZip.loadAsync(project.arrayBuffer);
  const text = await zip.file('project.json').async('text');
  const json = JSON.parse(text);

  assert.equal(json.costumes[0].baseLayerID, 0);
  assert.equal(json.costumes[0].baseLayerMD5, '');

  assert.equal(json.children[0].costumes[0].baseLayerID, 1);
  assert.equal(json.children[0].costumes[0].baseLayerMD5, '');
});
